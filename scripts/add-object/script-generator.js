/* Variable Set - Python script generator
   Builds a self-contained Python script that performs the FMC 3-step workflow:
     1. POST each Network/Host/Port Object to /object/{networks|hosts|protocolportobjects}
        and capture {id, name, type} for each
     2. GET  /object/variablesets/{id}?expanded=true
     3. For each new Variable entry, populate included.referenceObjects[] with the
        {id, name, type} captured in step 1, then PUT the Variable Set body back. */
(function () {
  'use strict';

  function buildPythonScript(payloads) {
    const ts = new Date().toISOString().replace(/[:.]/g, '-');
    /* JSON.stringify produces JSON syntax (false / true / null in lowercase),
       which is NOT valid as Python literals. Embedding it directly causes
       NameError. Solution: emit the JSON as a Python triple-quoted string,
       then parse it at runtime with json.loads(). */
    const netObjsJson  = JSON.stringify(payloads.networkObjects || [], null, 2);
    const portObjsJson = JSON.stringify(payloads.portObjects    || [], null, 2);
    const ipVarsJson   = JSON.stringify(payloads.ipVariables    || [], null, 2);
    const portVarsJson = JSON.stringify(payloads.portVariables  || [], null, 2);
    const objTotal = (payloads.networkObjects || []).length + (payloads.portObjects || []).length;
    const varTotal = (payloads.ipVariables    || []).length + (payloads.portVariables || []).length;

    const script = [
      '#!/usr/bin/env python3',
      '"""',
      'FMC Object + Variable Set Updater (auto-generated)',
      '==================================================',
      'Generated at:  ' + ts,
      'Objects to create:   ' + objTotal + ' (' +
        (payloads.networkObjects || []).length + ' network/host, ' +
        (payloads.portObjects || []).length + ' port)',
      'Variable entries:    ' + varTotal + ' (' +
        (payloads.ipVariables || []).length + ' network var, ' +
        (payloads.portVariables || []).length + ' port var)',
      '',
      '3-step FMC workflow:',
      '   Step A) POST Network/Host Objects   /object/networks | /object/hosts',
      '   Step B) POST Port Objects           /object/protocolportobjects',
      '   Step C) GET Variable Set, append entries that REFERENCE the just-',
      '           created objects via included.referenceObjects[], then PUT.',
      '',
      'Object and variable names are preserved exactly. IP/port values are',
      'random placeholders -- replace with real values in FMC GUI if needed.',
      '',
      'Already-existing Objects are reused (their id is fetched). Already-',
      'existing Variable entries inside the Variable Set are skipped.',
      '',
      'Usage:',
      '    pip install requests',
      '    python3 ' + 'fmc_variableset_' + ts + '.py',
      '"""',
      '',
      'from __future__ import annotations',
      '',
      'import getpass',
      'import json',
      'import sys',
      'from datetime import datetime',
      '',
      'try:',
      '    import requests',
      '    import urllib3',
      'except ImportError:',
      '    sys.exit("ERROR: install requests first: pip install requests")',
      '',
      'urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)',
      '',
      '_NETWORK_OBJECTS_JSON = r"""' + netObjsJson + '"""',
      '_PORT_OBJECTS_JSON = r"""' + portObjsJson + '"""',
      '_NETWORK_VARIABLES_JSON = r"""' + ipVarsJson + '"""',
      '_PORT_VARIABLES_JSON = r"""' + portVarsJson + '"""',
      '',
      'NETWORK_OBJECTS = json.loads(_NETWORK_OBJECTS_JSON)',
      'PORT_OBJECTS = json.loads(_PORT_OBJECTS_JSON)',
      'NETWORK_VARIABLES = json.loads(_NETWORK_VARIABLES_JSON)',
      'PORT_VARIABLES = json.loads(_PORT_VARIABLES_JSON)',
      '',
      '',
      'def prompt_required(question):',
      '    while True:',
      '        ans = input(question).strip()',
      '        if ans:',
      '            return ans',
      '        print("  Input required. Try again.")',
      '',
      '',
      'def login(host, user, password):',
      '    url = f"https://{host}/api/fmc_platform/v1/auth/generatetoken"',
      '    r = requests.post(url, auth=(user, password), verify=False, timeout=30)',
      '    r.raise_for_status()',
      '    token = r.headers.get("X-auth-access-token")',
      '    domain = r.headers.get("DOMAIN_UUID")',
      '    if not token or not domain:',
      '        raise RuntimeError(f"Auth failed: missing headers. Got: {dict(r.headers)}")',
      '    return token, domain',
      '',
      '',
      'def list_existing_objects(host, token, domain, endpoint):',
      '    """Return {name: id} for every object on the given endpoint."""',
      '    result = {}',
      '    offset, limit = 0, 1000',
      '    while True:',
      '        url = (f"https://{host}/api/fmc_config/v1/domain/{domain}"',
      '               f"/object/{endpoint}")',
      '        r = requests.get(url,',
      '                         params={"expanded": "false", "offset": offset, "limit": limit},',
      '                         headers={"X-auth-access-token": token},',
      '                         verify=False, timeout=60)',
      '        r.raise_for_status()',
      '        data = r.json()',
      '        for item in data.get("items", []):',
      '            result[item["name"]] = item["id"]',
      '        paging = data.get("paging", {})',
      '        count = paging.get("count", 0)',
      '        if offset + limit >= count:',
      '            break',
      '        offset += limit',
      '    return result',
      '',
      '',
      'def create_object(host, token, domain, endpoint, body):',
      '    url = (f"https://{host}/api/fmc_config/v1/domain/{domain}"',
      '           f"/object/{endpoint}")',
      '    r = requests.post(url, json=body,',
      '                      headers={"X-auth-access-token": token,',
      '                               "Content-Type": "application/json"},',
      '                      verify=False, timeout=60)',
      '    if r.status_code not in (200, 201):',
      '        raise RuntimeError(',
      '            f"POST /object/{endpoint} failed for {body[\u0027name\u0027]!r}: "',
      '            f"HTTP {r.status_code} {r.text[:300]}"',
      '        )',
      '    return r.json()["id"]',
      '',
      '',
      'def find_variableset_by_name(host, token, domain, vs_name):',
      '    url = (f"https://{host}/api/fmc_config/v1/domain/{domain}"',
      '           f"/object/variablesets")',
      '    r = requests.get(url, params={"expanded": "false", "limit": 1000},',
      '                     headers={"X-auth-access-token": token},',
      '                     verify=False, timeout=60)',
      '    r.raise_for_status()',
      '    items = r.json().get("items", [])',
      '    match = next((v for v in items if v["name"] == vs_name), None)',
      '    if not match:',
      '        available = ", ".join(v["name"] for v in items)',
      '        raise RuntimeError(',
      '            f"Variable Set {vs_name!r} not found. Available: [{available}]"',
      '        )',
      '    return match["id"]',
      '',
      '',
      'def get_variableset(host, token, domain, vs_id):',
      '    url = (f"https://{host}/api/fmc_config/v1/domain/{domain}"',
      '           f"/object/variablesets/{vs_id}")',
      '    r = requests.get(url,',
      '                     headers={"X-auth-access-token": token},',
      '                     verify=False, timeout=60)',
      '    r.raise_for_status()',
      '    body = r.json()',
      '    body.pop("metadata", None)',
      '    body.pop("links", None)',
      '    body.setdefault("variables", [])',
      '    return body',
      '',
      '',
      'def put_variableset(host, token, domain, vs_id, body):',
      '    """Try PUT first; on 405, fall back to PATCH (some FMC versions only',
      '       expose PATCH for /variablesets)."""',
      '    base = (f"https://{host}/api/fmc_config/v1/domain/{domain}"',
      '            f"/object/variablesets/{vs_id}")',
      '    headers = {"X-auth-access-token": token,',
      '               "Content-Type": "application/json"}',
      '    r = requests.put(base, json=body, headers=headers,',
      '                     verify=False, timeout=120)',
      '    if r.status_code == 405:',
      '        print("    PUT returned 405; trying PATCH fallback...")',
      '        r = requests.patch(base, json=body, headers=headers,',
      '                           verify=False, timeout=120)',
      '    if r.status_code == 405:',
      '        raise RuntimeError(',
      '            "HTTP 405 Method Not Allowed on both PUT and PATCH. "',
      '            "Your FMC version does not expose write operations on "',
      '            "/variablesets via REST. The Network/Port Objects were "',
      '            "still created successfully -- bind them manually in FMC GUI: "',
      '            "Objects > Object Management > Variable Set > Default-Set > Edit, "',
      '            "then add each variable using the just-created Object."',
      '        )',
      '    if r.status_code not in (200, 201):',
      '        raise RuntimeError(',
      '            f"Variable Set update failed: HTTP {r.status_code}. "',
      '            f"Response: {r.text[:500]}"',
      '        )',
      '    return r.json()',
      '',
      '',
      'def ensure_objects(host, token, domain, objects, label):',
      '    """POST each object; reuse id if it already exists.',
      '       Returns {name: {id, type}}."""',
      '    if not objects:',
      '        return {}, [], []',
      '    by_endpoint = {}',
      '    for o in objects:',
      '        by_endpoint.setdefault(o["endpoint"], []).append(o)',
      '',
      '    name_to_meta = {}',
      '    created, reused = [], []',
      '    for endpoint, items in by_endpoint.items():',
      '        print(f"[+] {label}: scanning existing /object/{endpoint} ...")',
      '        existing = list_existing_objects(host, token, domain, endpoint)',
      '        print(f"    existing: {len(existing)}")',
      '        for o in items:',
      '            name = o["body"]["name"]',
      '            objtype = o["objType"]',
      '            if name in existing:',
      '                name_to_meta[name] = {"id": existing[name], "type": objtype}',
      '                reused.append(name)',
      '            else:',
      '                new_id = create_object(host, token, domain, endpoint, o["body"])',
      '                name_to_meta[name] = {"id": new_id, "type": objtype}',
      '                created.append(name)',
      '                print(f"    + created {objtype:18} {name}")',
      '    if reused:',
      '        print(f"[!] {label} already existed (REUSE): {reused}")',
      '    return name_to_meta, created, reused',
      '',
      '',
      'def populate_references(var_entry, name_to_meta):',
      '    """Fill included.referenceObjects[] with real {id, name, type}."""',
      '    refs = var_entry.get("included", {}).get("referenceObjects", [])',
      '    for ref in refs:',
      '        meta = name_to_meta.get(ref["name"])',
      '        if not meta:',
      '            raise RuntimeError(',
      '                f"Cannot bind variable {var_entry[\u0027name\u0027]!r}: "',
      '                f"object {ref[\u0027name\u0027]!r} was not created/found."',
      '            )',
      '        ref["id"] = meta["id"]',
      '        ref["type"] = meta["type"]',
      '    return var_entry',
      '',
      '',
      'def main():',
      '    print("=" * 60)',
      '    print("FMC Object + Variable Set Updater")',
      '    print("=" * 60)',
      '    print(f"  Objects to create:   {len(NETWORK_OBJECTS) + len(PORT_OBJECTS)}")',
      '    print(f"    Network/Host:      {len(NETWORK_OBJECTS)}")',
      '    print(f"    Port:              {len(PORT_OBJECTS)}")',
      '    print(f"  Variable entries:    {len(NETWORK_VARIABLES) + len(PORT_VARIABLES)}")',
      '    print(f"    Network variables: {len(NETWORK_VARIABLES)}")',
      '    print(f"    Port variables:    {len(PORT_VARIABLES)}")',
      '    print()',
      '    print("Enter FMC connection details:")',
      '    fmc_host = prompt_required("  FMC IP or FQDN:        ")',
      '    fmc_user = prompt_required("  Username:              ")',
      '    fmc_pass = getpass.getpass("  Password:              ")',
      '    if not fmc_pass:',
      '        sys.exit("[!] Password is required.")',
      '    vs_name  = prompt_required("  Variable Set name:     ")',
      '',
      '    print(f"\\n[+] Logging in to {fmc_host}...")',
      '    try:',
      '        token, domain = login(fmc_host, fmc_user, fmc_pass)',
      '    except Exception as e:',
      '        sys.exit(f"[!] Login failed: {e}")',
      '    print(f"    OK (domain={domain})")',
      '',
      '    print("\\n--- Step A/B: ensure Network/Host/Port Objects exist ---")',
      '    try:',
      '        net_meta,  net_created,  net_reused  = ensure_objects(',
      '            fmc_host, token, domain, NETWORK_OBJECTS, "Network/Host")',
      '        port_meta, port_created, port_reused = ensure_objects(',
      '            fmc_host, token, domain, PORT_OBJECTS, "Port")',
      '    except Exception as e:',
      '        sys.exit(f"[!] Object provisioning failed: {e}")',
      '    name_to_meta = {**net_meta, **port_meta}',
      '',
      '    print(f"\\n--- Step C: update Variable Set {vs_name!r} ---")',
      '    print(f"[+] Looking up Variable Set {vs_name!r}...")',
      '    try:',
      '        vs_id = find_variableset_by_name(fmc_host, token, domain, vs_name)',
      '    except Exception as e:',
      '        sys.exit(f"[!] {e}")',
      '    print(f"    Found (id={vs_id})")',
      '',
      '    print("[+] Fetching current Variable Set body...")',
      '    try:',
      '        body = get_variableset(fmc_host, token, domain, vs_id)',
      '    except Exception as e:',
      '        sys.exit(f"[!] GET failed: {e}")',
      '    existing_var_names = {v["name"] for v in body.get("variables", [])}',
      '    print(f"    Current variable count: {len(existing_var_names)}")',
      '',
      '    new_entries = []',
      '    var_skipped = []',
      '    for entry in NETWORK_VARIABLES + PORT_VARIABLES:',
      '        if entry["name"] in existing_var_names:',
      '            var_skipped.append(entry["name"])',
      '            continue',
      '        try:',
      '            populate_references(entry, name_to_meta)',
      '        except Exception as e:',
      '            sys.exit(f"[!] {e}")',
      '        new_entries.append(entry)',
      '        existing_var_names.add(entry["name"])',
      '',
      '    if var_skipped:',
      '        print(f"[!] Variables already in Variable Set (SKIP): {var_skipped}")',
      '',
      '    if not new_entries:',
      '        print("[+] Nothing new to add. Variable Set already has all entries.")',
      '    else:',
      '        print(f"[+] Adding {len(new_entries)} new variable(s):")',
      '        for e in new_entries:',
      '            ref = e["included"]["referenceObjects"][0]',
      '            kind = "NetworkVar" if e["type"] == "NetworkVariable" else "PortVar"',
      '            print(f"    + {kind:11} {e[\u0027name\u0027]:24} -> {ref[\u0027type\u0027]} {ref[\u0027name\u0027]}")',
      '        body["variables"].extend(new_entries)',
      '        print(f"\\n[+] PUT /object/variablesets/{vs_id} ...")',
      '        try:',
      '            put_variableset(fmc_host, token, domain, vs_id, body)',
      '        except Exception as e:',
      '            sys.exit(f"[!] {e}")',
      '        print("    OK")',
      '',
      '    report = {',
      '        "timestamp": datetime.now().isoformat(),',
      '        "fmc_host": fmc_host,',
      '        "variable_set": vs_name,',
      '        "variable_set_id": vs_id,',
      '        "objects": {',
      '            "network_created": net_created,',
      '            "network_reused":  net_reused,',
      '            "port_created":    port_created,',
      '            "port_reused":     port_reused,',
      '        },',
      '        "variables": {',
      '            "added":   [e["name"] for e in new_entries],',
      '            "skipped": var_skipped,',
      '        },',
      '    }',
      '    out = f"fmc_variableset_report_{datetime.now().strftime(\u0027%Y%m%d_%H%M%S\u0027)}.json"',
      '    with open(out, "w", encoding="utf-8") as f:',
      '        json.dump(report, f, indent=2, ensure_ascii=False)',
      '    print(f"\\n[+] Report saved to {out}")',
      '    return 0',
      '',
      '',
      'if __name__ == "__main__":',
      '    sys.exit(main() or 0)',
      ''
    ];
    return script.join('\n');
  }

  function downloadScript(content, filename) {
    const blob = new Blob([content], { type: 'text/x-python;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 100);
  }

  window.AddObjectScriptGen = {
    buildPythonScript: buildPythonScript,
    downloadScript: downloadScript
  };
})();
